package com.novelreader.typeset

/**
 * 縦書きで1文字（書記素）をどう置くかの分類。
 *
 * なぜ enum で持つか: 「どの字を回すか／寄せるか」の決定を純Kotlin層に集約し、
 * 描画層（P2 GlyphRenderer）は決定に従って実行するだけにする分業のため
 * （fontFeatureSettings="vert" の効きは書体依存で不安定＝P0-1 実測。判断を描画に委ねない）。
 */
enum class CharClass {
    /** 正立（そのまま縦に置く）。漢字・仮名・全角英数字・約物「？！・」など。 */
    UPRIGHT,

    /** 90度回転して置く。括弧・長音・ダッシュ類・半角英字（欧文横倒し）など。 */
    ROTATE,

    /** 位置替え（右上寄せ等）。句読点「、。，．」と小書き仮名。 */
    PUNCT_REPOSITION,

    /** 縦中横（横倒しにせず横並びの小組みを1マスに収める）。半角の数字・英字・!? の2〜3字連。 */
    TATE_CHU_YOKO,
}

/**
 * 書記素→CharClass の分類器（純関数・文脈非依存）。
 *
 * なぜ文脈非依存か: ここは「1字を単独で見たときの既定の向き」を返す層。
 * 縦中横のラン文脈（1桁は正立・2〜3桁は縦中横・4桁以上は各字回転）は
 * ラン長を知る VerticalTypesetter 側が上書きする。分類器は半角英数字を
 * 一律 ROTATE（欧文横倒しの安全既定）に倒し、ラン文脈が精緻化する二層構成。
 *
 * 表の正本: P0 スパイク実測（vertical-mode-p0-measurements-2026-07-17.md）＋ JIS 縦組み慣行。
 */
object CharClassifier {

    /** 小書き仮名（ひらがな・カタカナ）。縦書きでは右上へ位置替えする（P0-1: vert で字形変化を確認）。 */
    private const val SMALL_KANA =
        "ぁぃぅぇぉっゃゅょゎゕゖァィゥェォッャュョヮヵヶ"

    /** PUNCT_REPOSITION 対象＝句読点＋小書き仮名＋縦書き用引用符（右上寄せ系の位置替え）。
     *  〝〞(U+301D/U+301E) は 2026-07-17 の追加実機計測で vert が両書体有効＝位置替え字形を持つと確認。
     *  〟(U+301F) は 2026-09-04 の実機計測で **vert 有効**と確定（default/serif とも字形が変わる）＝
     *  同族 301D/301E に揃えた推定が実測で裏付けられた（それまで 1 ヶ月半、推定が「計測済み」と
     *  書かれたまま潜伏していた）。実データの閉じは 301F（N8809BK 593 件）＝最も出る字が実測済みになった。
     *  ⚠️ 旧コメントは「閉じの実体は 〟U+301F でなく 〞U+301E」と断定していたが**逆**だった＝
     *  死んだオラクル（ToUnicode 逆引き）の出力を実体と取り違えていた。web 原文の閉じは 〟U+301F
     *  （N8809BK で開き 〝 593 件・閉じ 〟 593 件。ADR 0041 決定1 で抽出側を原文一致へ直した）。
     *  〞U+301E も収録したままにする＝同じ縦書き用引用符の族で位置替えの扱いは同一であり、
     *  他の生成器が出したときに落とす理由が無いため（収録の費用は Set 1 要素）。
     *  ⚠️ **欧文引用符 “”‘’(U+201C/201D/2018/2019) も同族として収録**（2026-09-03 の UAX#50 照合で追加）。
     *  UAX#50 の Vertical_Orientation は 4 字とも **Tr**＝〝〞〟(301D/301E/301F) と**同値**で、
     *  「変形（vert 等の縦字形）が主段・変形できない書体では回転が fallback 段」を指す。旧実装は表に無く
     *  UPRIGHT 既定＝**Tr のどちらの段でもない第3の状態**だった（実データ ” 5,416・“ 1,872・’ 29・‘ 2 件＝
     *  計 7,319 件で約物の最多クラスなのに向きが規範外）。同値の族を別扱いにする理由が無いので 301D 族へ揃える。
     *  ⚠️ **2026-09-04 の実機計測で 4 字とも vert 無効と確定**（default/serif とも字形が変わらない）＝
     *  Tr の主段（変形）は PGEM10 では出ず、**いま画面に出ているのは正立**（版面・マス割りは不変＝
     *  PaintFontMetrics が advance を変えるのは ROTATE のときだけ＝安全側に倒れたまま）。
     *  規範どおり fallback 段＝自前回転へ倒すかは**未裁定**（実データ 7,319 件の見えが変わる＝
     *  実機目視の裁定案件＝`awaiting-human.md` §3-2）。倒すなら MANUAL_ROTATE_REQUIRED へ足す＝
     *  「実測字だけの集合」という取り決めは今回の計測で満たしている。 */
    private val PUNCT_REPOSITION_CHARS: Set<Char> = ("、。，．〝〞〟“”‘’" + SMALL_KANA).toSet()

    /**
     * ROTATE 対象＝括弧18種＋長音/波/ダッシュ/約物の一部。
     * なぜここに「…‥；−」も入るか: P0-1 で vert が効かない（回してくれない）実測字＝
     * CharClassifier が回転判定を持つ必要がある（VertFeatureCoverage 参照）。
     */
    private val ROTATE_CHARS: Set<Char> = (
        "「」『』（）〔〕［］｛｝〈〉《》【】" +
            "ー～〜…‥—―‐–＝：；−－｜"
        ).toSet()

    /**
     * 書記素1つを分類する。未知文字は UPRIGHT に倒す（防御的既定）。
     * なぜ UPRIGHT 既定か: 縦書きで向きが不明な字も、正立なら最悪でも判読できる
     * （回転や位置替えを誤ると欠字同然に見えるため、既定は最も安全な正立）。
     */
    fun classify(grapheme: String): CharClass {
        if (grapheme.isEmpty()) return CharClass.UPRIGHT
        // 単一 BMP 文字だけがクラス表の対象。サロゲートペア・結合文字（length>1）は正立既定へ。
        if (grapheme.length == 1) {
            val c = grapheme[0]
            // 半角英数字は文脈非依存では欧文横倒し＝ROTATE（数字のラン文脈は Typesetter が上書き）。
            if (c in '0'..'9' || c in 'A'..'Z' || c in 'a'..'z') return CharClass.ROTATE
            if (c in PUNCT_REPOSITION_CHARS) return CharClass.PUNCT_REPOSITION
            if (c in ROTATE_CHARS) return CharClass.ROTATE
        }
        return CharClass.UPRIGHT
    }
}

/**
 * fontFeatureSettings="vert" が効かず、描画層で明示的に90度回転が必須な字の実測リスト。
 *
 * なぜ別立てか: これらは CharClass 上は ROTATE だが、P0-1 実測で vert フィーチャが
 * 縦字形を出さない（「‥」は default/serif で書体割れ）。P2 の GlyphRenderer が
 * 「vert に任せず必ず自前回転する字」を判定するために参照する。
 * 実測根拠: docs/knowledge/vert-feature-pgem10-coverage.md（P0-1 の 130 計測）。
 */
/**
 * 連続リーダー結合の規則（2026-07-17 実機フィードバック「……の点が等間隔にならない」への対処）。
 *
 * なぜ結合するか: 「…」を1字=1セルで独立描画すると、セル送り(em)とインク幅の差がセル境界の
 * 隙間として見え、……の点間隔が glyph 内と glyph 間で揃わない。同一リーダー字の連続を1ユニットに
 * まとめ一体で回転描画すれば、フォントが持つ字間設計がそのまま生き等間隔になる（――は連結罫線になる）。
 */
object LeaderJoin {
    /** 結合対象＝リーダー・ダッシュ類（すべて自前回転字）。同一字の連続のみ結合する（…‥ 混在は結合しない）。 */
    val CHARS: Set<Char> = setOf('…', '‥', '―', '—')

    /** 結合上限。結合ユニットは列を跨げない原子＝伸びすぎると列高を超えるための防御値。 */
    const val MAX_RUN = 4
}

object VertFeatureCoverage {
    /** vert が効かず自前回転が必須と実測された字（‥は書体割れ＝フォールバック必須の実証例）。
     *  ―(U+2015) は 2026-07-17 の追加実機計測で両書体無効と確認（――連続＝N9463BR 1006回の実データ字。
     *  放置すると実機でダッシュが横倒れにならず版面が壊れる）。—(U+2014)・‐(U+2010)・–(U+2013)・－(U+FF0D) は
     *  2026-09-04 の実機計測で **4 字とも vert 無効**と確定＝「同系ダッシュだから」の防御的推定が
     *  実測で裏付けられた（自前回転が要る側）。
     *  ⚠️ －(FF0D) は −(U+2212) の実測に相乗りで入った字で、2212 は実データ 0 件・FF0D が 1,874 件＝
     *  **出る方が未計測**という逆転だった。これも今回の計測で解消。 */
    val MANUAL_ROTATE_REQUIRED: Set<String> = setOf("…", "‥", "；", "−", "－", "―", "—", "‐", "–")

    /**
     * **実データに出るのに PGEM10 の vert 実機計測が無い字**の置き場（2026-09-04 に**空になった**）。
     *
     * 2026-09-03 の棚卸しで 24 字を積んだが、2026-09-04 に `Probe1FontFeature` のスパイクを PGEM10 で
     * 走らせて全字を実測し、推定だった根拠が実測へ置き換わった＝残高ゼロ。**枠は残す**——分類を足せる便と
     * 計測できる便は別で、また「推定で足した字」は出るため。
     *
     * なぜ枠を持つか: 分類は実機なしでも足せるが計測は足せない＝**未検証の申告だけが増える**。
     * 増えた申告を後で計測したときの消し忘れ（＝逆向きの嘘）まで含めて、突合を機械に持たせる。
     * この集合は VertProbeUnmeasuredTest が `test/resources/typeset/vert_probe_pgem10.jsonl` と
     * 突き合わせる＝計測済みの字がここに残っていれば赤くなる。
     * 実測の全結果と各字の解釈＝`docs/knowledge/vert-feature-pgem10-coverage.md`。
     */
    val UNMEASURED_IN_VERT_PROBE: Set<String> = emptySet()
}
